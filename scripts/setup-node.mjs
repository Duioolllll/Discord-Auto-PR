import { createHash } from 'node:crypto';
import { chmod, lstat, mkdir, mkdtemp, readFile, rename, rm, writeFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { dirname, join } from 'node:path';
import { fileURLToPath, URL } from 'node:url';
import { Buffer } from 'node:buffer';

const root = fileURLToPath(new URL('../', import.meta.url));
const pins = JSON.parse(await readFile(join(root, 'toolchain.json'), 'utf8'));
const local = join(root, '.local');
const folder = `node-v${pins.node}-linux-x64`;
const target = join(local, folder);
const bin = join(target, 'bin');
const quote = (value) => `'${value.replaceAll("'", "'\\''")}'`;
let stage = 'platform or private directory';
async function privateDirectory(path) {
  await mkdir(path, { mode: 0o700 }).catch((error) => {
    if (error.code !== 'EEXIST') throw error;
  });
  const info = await lstat(path);
  if (!info.isDirectory() || (process.getuid && info.uid !== process.getuid()))
    throw new Error('Tool directory must be owned by the current user and must not be a symlink');
  await chmod(path, 0o700);
}
async function install() {
  if (process.platform !== 'linux' || process.arch !== 'x64')
    throw new Error(
      'This helper supports Linux/WSL x64. See docs/getting-started.md for prerequisites.',
    );
  await privateDirectory(local);
  let present = false;
  try {
    const info = await lstat(target);
    if (!info.isDirectory() || (process.getuid && info.uid !== process.getuid()))
      throw new Error('Unsafe Node tool directory');
    present =
      execFileSync(join(bin, 'node'), ['--version'], {
        encoding: 'utf8',
        timeout: 10_000,
      }).trim() === `v${pins.node}`;
    if (!present)
      throw new Error(
        'Existing Node tool directory has an unexpected version; inspect it before retrying',
      );
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
  if (!present) {
    stage = 'official Node download';
    const temp = await mkdtemp(join(local, 'node-install-'));
    try {
      console.log(`Downloading official Node ${pins.node} LTS (SHA-256 pinned)…`);
      const response = await globalThis.fetch(
        `https://nodejs.org/dist/v${pins.node}/${folder}.tar.xz`,
        {
          signal: globalThis.AbortSignal.timeout(60_000),
          redirect: 'error',
        },
      );
      if (!response.ok || !response.body) throw new Error('Node distribution download failed');
      const chunks = [];
      let size = 0;
      for await (const chunk of response.body) {
        size += chunk.length;
        if (size > 64 * 1024 * 1024)
          throw new Error('Node distribution exceeds the download limit');
        chunks.push(chunk);
      }
      const archive = Buffer.concat(chunks);
      stage = 'Node SHA-256 verification';
      if (createHash('sha256').update(archive).digest('hex') !== pins.nodeLinuxX64Sha256)
        throw new Error('Node checksum mismatch; refusing to install');
      const file = join(temp, 'node.tar.xz');
      stage = 'Node extraction';
      await writeFile(file, archive, { mode: 0o600, flag: 'wx' });
      execFileSync('tar', ['-xJf', file, '-C', temp], { timeout: 60_000 });
      await rename(join(temp, folder), target);
    } finally {
      await rm(temp, { force: true, recursive: true });
    }
  }
  const corepackHome = join(local, 'corepack');
  stage = 'private tool caches';
  const npmCache = join(local, 'npm-cache');
  await privateDirectory(corepackHome);
  await privateDirectory(npmCache);
  const env = {
    ...process.env,
    PATH: `${bin}:${process.env.PATH ?? ''}`,
    COREPACK_HOME: corepackHome,
    NPM_CONFIG_CACHE: npmCache,
    NPM_CONFIG_PREFIX: target,
    COREPACK_ENABLE_DOWNLOAD_PROMPT: '0',
    NODE_USE_ENV_PROXY: '1',
  };
  stage = 'Corepack setup';
  execFileSync(join(bin, 'corepack'), ['enable', '--install-directory', bin], {
    env,
    stdio: 'pipe',
    timeout: 30_000,
  });
  stage = 'signed pnpm download';
  console.log(`Preparing pinned pnpm ${pins.pnpm}…`);
  execFileSync(join(bin, 'corepack'), ['prepare', `pnpm@${pins.pnpm}`, '--activate'], {
    env,
    stdio: 'pipe',
    timeout: 60_000,
  });
  const manager = execFileSync(join(bin, 'pnpm'), ['--version'], {
    env,
    encoding: 'utf8',
    timeout: 30_000,
  }).trim();
  if (manager !== pins.pnpm) throw new Error('pnpm version mismatch');
  const activation = join(local, 'activate-toolchain.sh');
  stage = 'activation file';
  const temp = await mkdtemp(join(local, 'activation-'));
  try {
    await writeFile(
      join(temp, 'activate.sh'),
      `# Generated by scripts/setup-node.mjs\nexport PATH=${quote(bin)}:"$PATH"\nexport COREPACK_HOME=${quote(corepackHome)}\nexport NPM_CONFIG_CACHE=${quote(npmCache)}\nexport NPM_CONFIG_PREFIX=${quote(target)}\n`,
      { mode: 0o600, flag: 'wx' },
    );
    // Replace a symlink itself rather than following it.
    await rename(join(temp, 'activate.sh'), activation);
  } finally {
    await rm(temp, { force: true, recursive: true });
  }
  console.log(
    `Ready: Node ${pins.node} LTS · pnpm ${manager}. System installations and Codex profiles were preserved.`,
  );
  console.log(`Run: source ${quote(join(dirname(activation), 'activate-toolchain.sh'))}`);
}
await install().catch(() => {
  console.error(
    `Toolchain setup failed at ${stage}. Check Linux x64 prerequisites, HTTPS connectivity, file ownership and pinned checksums. No credentials are needed.`,
  );
  process.exitCode = 1;
});
